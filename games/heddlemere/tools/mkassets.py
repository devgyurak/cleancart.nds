"""Generate every Heddlemere asset.

    mkassets.py <gen_dir> <nitrofs_dir>

<gen_dir>/assets.c|h  data linked into the ARM9 binary
<gen_dir>/icon.bmp    banner icon for ndstool
<nitrofs_dir>/*       files loaded from the cartridge at run time

All output is a pure function of this source tree.
"""

import glob
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import order_check  # noqa: E402
from cvtools import audio, codec, images, hmart  # noqa: E402
from hmorder import model as hm_model, pack as hm_pack  # noqa: E402
from cvtools.gfx import u16s, bmp_4bpp  # noqa: E402


class CWriter:
    def __init__(self):
        self.c = []
        self.h = []

    def blob(self, name, data, comment=''):
        data = bytes(data)
        while len(data) % 4:
            data += b'\0'
        if comment:
            self.h.append('// %s' % comment)
        self.h.append('extern const uint8_t %s[];' % name)
        self.h.append('#define %s_SIZE %du' % (name.upper(), len(data)))
        lines = []
        for i in range(0, len(data), 24):
            lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
        self.c.append('const uint8_t %s[] __attribute__((aligned(4))) = {\n%s\n};\n'
                      % (name, '\n'.join(lines)))

    def define(self, name, value):
        self.h.append('#define %s %s' % (name, value))

    def raw_h(self, text):
        self.h.append(text)

    def raw_c(self, text):
        self.c.append(text)

    def write(self, gen):
        hdr = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#ifndef CV_ASSETS_H', '#define CV_ASSETS_H', '',
               '#include <stdint.h>', '#include "cv_ipc.h"', '']
        with open(os.path.join(gen, 'assets.h'), 'w') as f:
            f.write('\n'.join(hdr + self.h + ['', '#endif', '']))
        src = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#include "assets.h"', '']
        with open(os.path.join(gen, 'assets.c'), 'w') as f:
            f.write('\n'.join(src) + '\n' + '\n'.join(self.c))


def pack(parts):
    """CVPK container: u32 magic, u32 count, {u32 off, u32 size}[count], data."""
    out = bytearray(struct.pack('<II', 0x4B505643, len(parts)))
    table_at = len(out)
    out += b'\0' * (8 * len(parts))
    for i, p in enumerate(parts):
        while len(out) % 4:
            out.append(0)
        struct.pack_into('<II', out, table_at + 8 * i, len(out), len(p))
        out += p
    while len(out) % 4:
        out.append(0)
    return bytes(out)


def lz(data):
    blob = codec.lz77(data)
    assert codec.lz77_decode(blob) == bytes(data), 'lz77 self-check failed'
    return blob


def heddlemere_icon():
    """32x32 banner icon: a square of woven cloth, four coloured weft threads over a dark warp, in a frame."""
    pal = [(0, 0, 0), (14, 14, 30), (60, 56, 80), (200, 70, 80), (225, 170, 60), (70, 150, 210),
           (110, 180, 110), (235, 230, 220)] + [(0, 0, 0)] * 8
    pix = [[1] * 32 for _ in range(32)]
    for y in range(2, 30):
        for x in range(2, 30):
            if x in (2, 29) or y in (2, 29):
                pix[y][x] = 7                           # the frame
                continue
            band = (y - 3) // 7                         # four weft colours, seven lines each
            warp = (x - 3) // 3 % 2 == 0                # warp threads, three pixels wide
            over = ((x - 3) // 3 + (y - 3) // 2) % 2    # the weft goes over or under the warp
            pix[y][x] = (3, 4, 5, 6)[min(band, 3)] if over else 2 if warp else 1
    return pix, pal


def write(path, data):
    with open(path, 'wb') as f:
        f.write(data)


def main():
    gen, nitro = sys.argv[1], sys.argv[2]
    os.makedirs(gen, exist_ok=True)
    os.makedirs(nitro, exist_ok=True)
    w = CWriter()

    # --- 2D ---------------------------------------------------------------
    w.blob('cv_font_tiles', images.font_tiles(), 'Font, 4bpp, chars 0x20-0x5F')
    w.blob('cv_ui_tiles', images.ui_tiles(), 'Window/gauge tiles, 4bpp')
    w.blob('cv_ui_pal', u16s([0]) + images.palette_bytes(images.UI_PALETTE)[2:])

    tiles, entries, pal = hmart.title_lettering()
    w.blob('cv_title_tiles', tiles, 'title lettering, 4bpp, %d x %d tiles' % (hmart.COLS, hmart.ROWS))
    w.blob('cv_title_map', u16s(entries), 'title lettering map entries, raster order, palette line %d' % hmart.PAL_LINE)
    w.blob('cv_title_pal', pal, 'title lettering palette line (16 colours)')
    w.raw_h('#define HM_TITLE_COLS %d' % hmart.COLS)
    w.raw_h('#define HM_TITLE_ROWS %d' % hmart.ROWS)
    w.raw_h('#define HM_TITLE_PAL_LINE %d' % hmart.PAL_LINE)
    w.raw_h('#define HM_TITLE_BLANK %d' % hmart.BLANK_TILE)
    w.raw_h('#define HM_TITLE_PANEL %d' % hmart.PANEL_TILE)
    # --- Loom orders ------------------------------------------------------
    # The build stops when an order fails the checker (tools/order_check.py).
    here = os.path.dirname(os.path.abspath(__file__))
    files = sorted(glob.glob(os.path.join(here, 'orders', 'ch*.txt')))
    orders = order_check.load(files)
    rows, ok = order_check.check(orders)
    if not ok:
        for r in rows:
            for m in r['problems']:
                print('order %s: %s' % (r['id'], m), file=sys.stderr)
        sys.exit('loom orders failed the checker')
    w.blob('cv_orders', hm_pack.pack(orders), 'loom orders and par (tools/hmorder/pack.py)')
    w.define('HM_NUM_ORDERS', len(orders))
    w.define('HM_CHAPTERS', len(hm_model.CHAPTERS))
    w.define('HM_ROWS', hm_model.ROWS)
    w.define('HM_COLS', hm_model.COLS)
    w.define('HM_NFIELDS', hm_model.NFIELDS)
    w.define('HM_LINE_CYCLES', hm_model.LINE_CYCLES)
    w.define('HM_LEVER_LINES', hm_model.LEVER_LINES)
    w.define('HM_DYE_FIRST', hm_model.DYE_FIRST)
    w.define('HM_DYE_LAST', hm_model.DYE_LAST)
    w.raw_h('extern const uint8_t hm_col_count[HM_COLS];')
    w.raw_c('const uint8_t hm_col_count[HM_COLS] = { %s };\n' % ', '.join(str(n) for n in hm_model.COUNTS))
    w.raw_h('extern const uint8_t hm_active_cols[HM_CHAPTERS + 1];   // bit mask of the columns a chapter turns')
    w.raw_c('const uint8_t hm_active_cols[HM_CHAPTERS + 1] = { 0, %s };\n'
            % ', '.join(str(sum(1 << c for c in hm_model.ACTIVE[ch])) for ch in range(1, len(hm_model.CHAPTERS) + 1)))
    w.raw_h('extern const uint16_t hm_program_ticks[4];   // GX cycles of the four heddle programs')
    w.raw_c('const uint16_t hm_program_ticks[4] = { %s };\n' % ', '.join(str(t) for t in hm_model.TICKS))
    w.raw_h('extern const uint16_t hm_dye_line[6];')
    w.raw_c('const uint16_t hm_dye_line[6] = { %s };\n' % ', '.join(str(t) for t in hm_model.DYE_LINES))
    w.raw_h('extern const char *const hm_col_title[HM_COLS];')
    w.raw_c('const char *const hm_col_title[HM_COLS] = { %s };\n' % ', '.join('"%s"' % c[1] for c in hm_model.COLUMNS))
    w.raw_h('extern const char *const hm_col_value[HM_COLS][6];')
    rows = ['    { %s },' % ', '.join('"%s"' % v for v in c[2] + [''] * (6 - len(c[2]))) for c in hm_model.COLUMNS]
    w.raw_c('const char *const hm_col_value[HM_COLS][6] = {\n%s\n};\n' % '\n'.join(rows))
    w.raw_h('extern const char *const hm_chapter_name[%d];' % len(hm_model.CHAPTERS))
    w.raw_c('const char *const hm_chapter_name[%d] = { %s };\n'
            % (len(hm_model.CHAPTERS), ', '.join('"%s"' % c for c in hm_model.CHAPTERS)))

    # --- Sound ------------------------------------------------------------
    samples = audio.make_samples()
    for i, s in enumerate(samples):
        audio.SAMPLE_IDS[s.name] = i
        w.define('CV_SFX_%s' % s.name.upper(), i)
    songs = audio.make_songs()
    sample_rows = []
    for i, s in enumerate(samples):
        if s.data:
            w.blob('cv_smp_%s' % s.name, s.data)
            ptr = 'cv_smp_%s' % s.name
        else:
            ptr = '0'
        sample_rows.append('    { %s, %du, %du, %du, %d, %d },'
                           % (ptr, s.words, s.loop & 0xFFFF, s.rate & 0xFFFF, s.fmt, s.volume))
    song_rows = []
    for i, (name, tracks, tempo) in enumerate(songs):
        w.define('CV_SONG_%s' % name.upper(), i)
        ptrs = []
        for t, data in enumerate(tracks):
            if data:
                w.blob('cv_song_%s_%d' % (name, t), data)
                ptrs.append('cv_song_%s_%d' % (name, t))
            else:
                ptrs.append('0')
        song_rows.append('    { { %s }, %d, 0 },' % (', '.join(ptrs), tempo))
    w.define('CV_NUM_SAMPLES', len(samples))
    w.define('CV_NUM_SONGS', len(songs))
    w.raw_h('extern const CvSoundBank cv_sound_bank;')
    w.raw_c('static const CvSample samples[] = {\n%s\n};\n' % '\n'.join(sample_rows))
    w.raw_c('static const CvSong songs[] = {\n%s\n};\n' % '\n'.join(song_rows))
    w.raw_c('const CvSoundBank cv_sound_bank __attribute__((aligned(4))) = '
            '{ CV_BANK_MAGIC, %d, %d, samples, songs };\n' % (len(samples), len(songs)))
    names = ', '.join('"%s"' % s.name.upper() for s in samples)
    w.raw_h('extern const char *const cv_sample_names[];')
    w.raw_c('const char *const cv_sample_names[] = { %s };\n' % names)
    names = ', '.join('"%s"' % n.upper() for (n, _, _) in songs)
    w.raw_h('extern const char *const cv_song_names[];')
    w.raw_c('const char *const cv_song_names[] = { %s };\n' % names)

    # --- Cartridge files (NitroFS) ----------------------------------------
    # Licence texts are copied in by the Makefile. cart_init() checks the
    # probe file's CRC to find out whether NitroFS works on the cart in use.
    w.define('CV_STREAM_RATE', 0)
    probe = bytes((i * 7 + 3) & 0xFF for i in range(2048))
    write(os.path.join(nitro, 'probe.bin'), probe)
    w.define('CV_PROBE_CRC16', '0x%04x' % codec.crc16(probe))

    w.write(gen)

    pix, pal = heddlemere_icon()
    bmp_4bpp(os.path.join(gen, 'icon.bmp'), pix, pal)


if __name__ == '__main__':
    main()
