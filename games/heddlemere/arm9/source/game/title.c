// Title screen: the name, woven in six thread colours (a generated tile BG on BG2), over a cloth of six raster-woven
// bands (gfx/loom.c, BG1) whose threads and weaves drift.
//
// Layers on the top screen (engine A, scene_text_screens()): BG0 = text (char base 0, map block 31,
// priority 0), BG2 = lettering (char base 2 = 0x06008000, map block 30 = 0x0600F000, palette line 8,
// priority 1, below the text; the cloth is BG1 at priority 2). The font is 82 tiles at
// 0x06000000, so the lettering tiles end well below block 30.

#include <nds.h>

#include "assets.h"
#include "core/hw.h"
#include "core/input.h"
#include "core/qa.h"
#include "core/save.h"
#include "core/snd.h"
#include "core/sys.h"
#include "game/scenes.h"
#include "gfx/fx.h"
#include "gfx/loom.h"
#include "gfx/text.h"

#define MAIN_BG ((u8 *)0x06000000)
#define LETTER_CHAR_BASE 2     // 16 KB units: 0x06008000
#define LETTER_MAP_BLOCK 30    // 2 KB units: 0x0600F000
#define LETTER_ROW 8           // first map row of the lettering (rows 8-11, y 64-95)
#define PANEL_ROW 18          // rows 18-23 (y 144-191): the text sits on a dark panel
#define LETTER_COL ((32 - HM_TITLE_COLS) / 2)

_Static_assert(HM_TITLE_COLS <= 32, "the lettering must fit one map row");

static CvText main_text, sub_text;

static void load_lettering(void)
{
    swiCopy(cv_title_tiles, MAIN_BG + LETTER_CHAR_BASE * 0x4000, CV_TITLE_TILES_SIZE / 2 | COPY_MODE_HWORD);
    swiCopy(cv_title_pal, CV_PAL_BG_MAIN + HM_TITLE_PAL_LINE * 16, CV_TITLE_PAL_SIZE / 2 | COPY_MODE_HWORD);
    u16 *map = (u16 *)(MAIN_BG + LETTER_MAP_BLOCK * 2048);
    // Empty cells point at the blank tile (tile 0 is a lettering tile); rows 18-23 are a dark panel
    // for the bottom text.
    for (int i = 0; i < 32 * 32; i++)
        map[i] = HM_TITLE_BLANK | HM_TITLE_PAL_LINE << 12;
    // A dark strip behind the lettering, one tile row above and below it, so the cloth does not eat the letters.
    for (int i = (LETTER_ROW - 1) * 32; i < (LETTER_ROW + HM_TITLE_ROWS + 1) * 32; i++)
        map[i] = HM_TITLE_PANEL | HM_TITLE_PAL_LINE << 12;
    for (int i = PANEL_ROW * 32; i < 24 * 32; i++)
        map[i] = HM_TITLE_PANEL | HM_TITLE_PAL_LINE << 12;
    const u16 *src = (const u16 *)cv_title_map;
    for (int r = 0; r < HM_TITLE_ROWS; r++)
        for (int c = 0; c < HM_TITLE_COLS; c++)
            map[(LETTER_ROW + r) * 32 + LETTER_COL + c] = src[r * HM_TITLE_COLS + c];
    REG_BG2CNT = BG_TILE_BASE(LETTER_CHAR_BASE) | BG_MAP_BASE(LETTER_MAP_BLOCK) | BG_PRIORITY(1);
    REG_BG2HOFS = 0;
    REG_BG2VOFS = 0;
    REG_DISPCNT |= DISPLAY_BG2_ACTIVE;
}

HmScene scene_title(void)
{
    scene_text_screens(&main_text, &sub_text);
    load_lettering();
    loom_begin(0, 6, 32);
    for (int r = 0; r < 6; r++)
        loom_row(r, r, (r * 5 + 1) & 3);
    loom_show(false);

    text_center(&main_text, 18, TP_GRAY, "A PUNCH CARD LOOM");
    text_center(&main_text, 21, TP_WHITE, "PRESS START");
    text_center(&main_text, 23, TP_GRAY, "X: CREDITS");

    text_center(&sub_text, 8, TP_WHITE, "APACHE-2.0 SOURCE");
    text_center(&sub_text, 10, TP_GRAY, "ALL ASSETS GENERATED BY CODE");
    text_printf(&sub_text, 1, 21, TP_GRAY, "ARM7 CORE: %s",
                sys_ipcsync_seen() == CV_SYNC_ARM7_READY ? "MOUNTED" : "WAITING");
    text_printf(&sub_text, 1, 22, TP_GRAY, "SAVE CHIP: %s", save_type_name());

    snd_bgm(CV_SONG_CLERESTORY);
    fx_bright(FX_BOTH, -16);
    for (int f = 0;; f++)
    {
        // Fade in inside the loop (fx_fade_in() only waits for vblanks).
        if (f < 20)
            fx_bright(FX_BOTH, -(16 * (19 - f) / 20));
        // The cloth drifts: every 90 frames the threads move one band down.
        if (f % 90 == 0)
            for (int r = 0; r < 6; r++)
                loom_row(r, (r + f / 90) % 6, ((r + f / 90) * 5 + 1) & 3);
        // Blink the prompt.
        text_center(&main_text, 21, (f / 30) & 1 ? TP_GRAY : TP_WHITE, "PRESS START");
        scene_frame_end();
        if (qa_title_poll() || qa_marker_poll())
        {
            // Hidden auto QA mode (core/qa.h): the order list, like Start.
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_SELECT;
        }
        // X opens the credits, but L+R+X is the start of the QA combo: with L or R
        // held X is left alone (press L and R first, then X).
        if (cv_in.pressed & KEY_START)
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_SELECT;
        }
        if ((cv_in.pressed & KEY_X) && !(cv_in.held & (KEY_L | KEY_R)))
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_CREDITS;
        }
    }
}
