// Title screen: the 3D rose window (gfx/glass.c, a preset of its own) turning behind the
// name cut in glass (a generated tile BG), with the clerestory theme.
//
// Layers on the top screen (engine A, entered through display_3d_top(), the same way as the
// play scene):  BG0 = 3D rose (priority 1), BG1 = text (char base 0, map block 31, priority 0),
// BG2 = lettering (char base 2 = 0x06008000, map block 30 = 0x0600F000, palette line 8,
// priority 0, below the text because it has the higher BG number). The font is 82 tiles at
// 0x06000000, so the lettering tiles (96 x 32 bytes) end at 0x06008C00, then a blank and a panel tile, well below block 30.

#include <nds.h>

#include "assets.h"
