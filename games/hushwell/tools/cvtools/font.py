FIRST = 0x20
LAST = 0x5F


def glyph_rows(ch):
    """Return 8 rows of 8 bits (bit 7 = leftmost) for a character cell."""
    rows = GLYPHS.get(ch, GLYPHS['?'])
    assert len(rows) == 7, ch
    out = []
    for r in rows:
        assert len(r) == 5, (ch, r)
        bits = 0
        for i, c in enumerate(r):
            if c == '#':
                bits |= 0x80 >> (i + 1)  # one pixel left margin
        out.append(bits)
    out.append(0)
    return out


def font_pixels(ch):
    """8x8 list of 0/1 pixels."""
    return [[(row >> (7 - x)) & 1 for x in range(8)] for row in glyph_rows(ch)]


def all_chars():
    return [chr(c) for c in range(FIRST, LAST + 1)]
