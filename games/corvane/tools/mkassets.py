"""Generate every Corvane asset.

    mkassets.py <gen_dir> <nitrofs_dir>

<gen_dir>/assets.c|h  data linked into the ARM9 binary
<gen_dir>/icon.bmp    banner icon for ndstool
<nitrofs_dir>/*       files loaded from the cartridge at run time

All output is a pure function of this source tree.
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from cvtools import audio, codec, images, stages  # noqa: E402
from cvtools.gfx import u16s, bmp_4bpp  # noqa: E402


class CWriter:
    def __init__(self):
        self.c = []
        self.h = []

    def blob(self, name, data, comment=''):
        data = bytes(data)
        while len(data) % 4:
            data += b'\0'
        if comment:
            self.h.append('// %s' % comment)
        self.h.append('extern const uint8_t %s[];' % name)
        self.h.append('#define %s_SIZE %du' % (name.upper(), len(data)))
        lines = []
        for i in range(0, len(data), 24):
            lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
        self.c.append('const uint8_t %s[] __attribute__((aligned(4))) = {\n%s\n};\n'
                      % (name, '\n'.join(lines)))

    def define(self, name, value):
        self.h.append('#define %s %s' % (name, value))

    def raw_h(self, text):
        self.h.append(text)

    def raw_c(self, text):
        self.c.append(text)

    def write(self, gen):
        hdr = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#ifndef CV_ASSETS_H', '#define CV_ASSETS_H', '',
               '#include <stdint.h>', '#include "cv_ipc.h"', '']
        with open(os.path.join(gen, 'assets.h'), 'w') as f:
            f.write('\n'.join(hdr + self.h + ['', '#endif', '']))
        src = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#include "assets.h"', '']
        with open(os.path.join(gen, 'assets.c'), 'w') as f:
            f.write('\n'.join(src) + '\n' + '\n'.join(self.c))


def pack(parts):
    """CVPK container: u32 magic, u32 count, {u32 off, u32 size}[count], data."""
    out = bytearray(struct.pack('<II', 0x4B505643, len(parts)))
    table_at = len(out)
    out += b'\0' * (8 * len(parts))
    for i, p in enumerate(parts):
        while len(out) % 4:
            out.append(0)
        struct.pack_into('<II', out, table_at + 8 * i, len(out), len(p))
        out += p
    while len(out) % 4:
        out.append(0)
    return bytes(out)


def lz(data):
    blob = codec.lz77(data)
    assert codec.lz77_decode(blob) == bytes(data), 'lz77 self-check failed'
    return blob


def write(path, data):
    with open(path, 'wb') as f:
        f.write(data)


def main():
    gen, nitro = sys.argv[1], sys.argv[2]
    os.makedirs(gen, exist_ok=True)
    os.makedirs(nitro, exist_ok=True)
    w = CWriter()

    # --- 2D ---------------------------------------------------------------
    w.blob('cv_font_tiles', images.font_tiles(), 'Font, 4bpp, chars 0x20-0x5F')
    w.blob('cv_ui_tiles', images.ui_tiles(), 'Window/gauge tiles, 4bpp')
    w.blob('cv_ui_pal', u16s([0]) + images.palette_bytes(images.UI_PALETTE)[2:])
    sheet, index = images.sprite_sheet()
    w.blob('cv_sprite_tiles', sheet, '4bpp sprite sheet, 1D mapping')
    w.blob('cv_sprite_pal', images.palette_bytes(images.SPRITE_PALETTE))
    for name, (tile, sw, sh) in sorted(index.items()):
        w.define('CV_SPR_%s' % name.upper(), tile)
    w.blob('cv_meteor_tiles', images.meteor_8bpp(), '8bpp meteor (ext palettes)')
    w.blob('cv_meteor_extpal', b''.join(images.meteor_palettes()), '4 x 256-colour OBJ ext palettes')
    w.blob('cv_cutin_bitmap', images.cutin_bitmap(), '64x64 16bpp bitmap OBJ')
    w.blob('cv_radar_grid', images.radar_grid(), '64x64 4bpp radar grid tiles')
    w.blob('cv_radar_ring', images.hud_radar_ring(), '128x128 4bpp radar ring tiles')
    logo = images.logo_bitmap()
    w.blob('cv_logo_lz', lz(logo), '256x256 8bpp logo, LZ77')
    w.blob('cv_logo_pal', images.logo_palette())

    # --- 3D ---------------------------------------------------------------
    tex = images.textures()
    for name in sorted(tex):
        data, pal, tw, th = tex[name]
        w.blob('cv_tex_%s' % name, data, 'texture %dx%d' % (tw, th))
        if pal:
            w.blob('cv_tex_%s_pal' % name, pal)
        else:
            w.define('CV_TEX_%s_PAL_SIZE' % name.upper(), 0)
    w.blob('cv_toon_table', images.toon_table())

    # --- Sound ------------------------------------------------------------
    samples = audio.make_samples()
    for i, s in enumerate(samples):
        audio.SAMPLE_IDS[s.name] = i
        w.define('CV_SFX_%s' % s.name.upper(), i)
    songs = audio.make_songs()
    sample_rows = []
    for i, s in enumerate(samples):
        if s.data:
            w.blob('cv_smp_%s' % s.name, s.data)
            ptr = 'cv_smp_%s' % s.name
        else:
            ptr = '0'
        sample_rows.append('    { %s, %du, %du, %du, %d, %d },'
                           % (ptr, s.words, s.loop & 0xFFFF, s.rate & 0xFFFF, s.fmt, s.volume))
    song_rows = []
    for i, (name, tracks, tempo) in enumerate(songs):
        w.define('CV_SONG_%s' % name.upper(), i)
        ptrs = []
        for t, data in enumerate(tracks):
            if data:
                w.blob('cv_song_%s_%d' % (name, t), data)
                ptrs.append('cv_song_%s_%d' % (name, t))
            else:
                ptrs.append('0')
        song_rows.append('    { { %s }, %d, 0 },' % (', '.join(ptrs), tempo))
    w.define('CV_NUM_SAMPLES', len(samples))
    w.define('CV_NUM_SONGS', len(songs))
    w.raw_h('extern const CvSoundBank cv_sound_bank;')
    w.raw_c('static const CvSample samples[] = {\n%s\n};\n' % '\n'.join(sample_rows))
    w.raw_c('static const CvSong songs[] = {\n%s\n};\n' % '\n'.join(song_rows))
    w.raw_c('const CvSoundBank cv_sound_bank __attribute__((aligned(4))) = '
            '{ CV_BANK_MAGIC, %d, %d, samples, songs };\n' % (len(samples), len(songs)))
    names = ', '.join('"%s"' % s.name.upper() for s in samples)
    w.raw_h('extern const char *const cv_sample_names[];')
    w.raw_c('const char *const cv_sample_names[] = { %s };\n' % names)
    names = ', '.join('"%s"' % n.upper() for (n, _, _) in songs)
    w.raw_h('extern const char *const cv_song_names[];')
    w.raw_c('const char *const cv_song_names[] = { %s };\n' % names)

    # --- Cartridge files (NitroFS) ----------------------------------------
    # Stages: procedural layouts, unless tools/stages/stageN.json (written by
    # tools/stage_editor.py) overrides one.
    here = os.path.dirname(os.path.abspath(__file__))
    for st in stages.STAGES:
        override = os.path.join(here, 'stages', 'stage%d.json' % st['n'])
        if os.path.exists(override):
            import json
            with open(override) as f:
                blob = stages.from_json(json.load(f))
        else:
            blob = stages.build(st)
        write(os.path.join(nitro, 'stage%d.lz' % st['n']), lz(blob))
    write(os.path.join(nitro, 'title.lz'), lz(images.title_bitmap()))
    write(os.path.join(nitro, 'nebula.pk'), pack([lz(images.nebula()), images.nebula_palette()]))
    tiles, mp, pal = images.sky_affine()
    write(os.path.join(nitro, 'sky.pk'), pack([lz(tiles), mp, pal]))
    tiles, mp, pal = images.cloud_layer()
    write(os.path.join(nitro, 'clouds.pk'), pack([lz(tiles), mp, pal]))
    tiles, mp, pal = images.sea_layer()
    write(os.path.join(nitro, 'sea.pk'), pack([lz(tiles), mp, pal]))
    for i, scene in enumerate(images.BRIEF_SCENES):
        tiles, idx, pal = images.briefing_art(scene)
        write(os.path.join(nitro, 'brief%d.pk' % (i + 1)),
              pack([lz(tiles), u16s(idx), pal]))
    stream, rate = audio.make_stream()
    write(os.path.join(nitro, 'stream.pcm'), stream)
    w.define('CV_STREAM_RATE', rate)
    for i, blob in enumerate(stages.demo_replays()):
        write(os.path.join(nitro, 'demo%d.rpl' % (i + 1)), blob)
    # A small file with a known CRC for the raw cart-DMA demo.
    probe = bytes((i * 7 + 3) & 0xFF for i in range(2048))
    write(os.path.join(nitro, 'probe.bin'), probe)
    w.define('CV_PROBE_CRC16', '0x%04x' % codec.crc16(probe))

    w.write(gen)

    pix, pal = images.icon()
    bmp_4bpp(os.path.join(gen, 'icon.bmp'), pix, pal)


if __name__ == '__main__':
    main()
