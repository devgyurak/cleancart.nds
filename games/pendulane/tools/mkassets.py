"""Generate every Pendulane asset.

    mkassets.py <gen_dir> <nitrofs_dir>

<gen_dir>/assets.c|h  data linked into the ARM9 binary
<gen_dir>/icon.bmp    banner icon for ndstool
<nitrofs_dir>/*       files loaded from the cartridge at run time

All output is a pure function of this source tree.
"""

import math
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import glob  # noqa: E402

from pdorder import check as pd_check, model as pd_model  # noqa: E402
from cvtools import audio, codec, images, pdart  # noqa: E402
from cvtools.gfx import u16s, bmp_4bpp  # noqa: E402


class CWriter:
    def __init__(self):
        self.c = []
        self.h = []

    def blob(self, name, data, comment=''):
        data = bytes(data)
        while len(data) % 4:
            data += b'\0'
        if comment:
            self.h.append('// %s' % comment)
        self.h.append('extern const uint8_t %s[];' % name)
        self.h.append('#define %s_SIZE %du' % (name.upper(), len(data)))
        lines = []
        for i in range(0, len(data), 24):
            lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
        self.c.append('const uint8_t %s[] __attribute__((aligned(4))) = {\n%s\n};\n'
                      % (name, '\n'.join(lines)))

    def define(self, name, value):
        self.h.append('#define %s %s' % (name, value))

    def raw_h(self, text):
        self.h.append(text)

    def raw_c(self, text):
        self.c.append(text)

    def write(self, gen):
        hdr = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#ifndef CV_ASSETS_H', '#define CV_ASSETS_H', '',
               '#include <stdint.h>', '#include "cv_ipc.h"', '']
        with open(os.path.join(gen, 'assets.h'), 'w') as f:
            f.write('\n'.join(hdr + self.h + ['', '#endif', '']))
        src = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#include "assets.h"', '']
        with open(os.path.join(gen, 'assets.c'), 'w') as f:
            f.write('\n'.join(src) + '\n' + '\n'.join(self.c))


def pack(parts):
    """CVPK container: u32 magic, u32 count, {u32 off, u32 size}[count], data."""
    out = bytearray(struct.pack('<II', 0x4B505643, len(parts)))
    table_at = len(out)
    out += b'\0' * (8 * len(parts))
    for i, p in enumerate(parts):
        while len(out) % 4:
            out.append(0)
        struct.pack_into('<II', out, table_at + 8 * i, len(out), len(p))
        out += p
    while len(out) % 4:
        out.append(0)
    return bytes(out)


def lz(data):
    blob = codec.lz77(data)
    assert codec.lz77_decode(blob) == bytes(data), 'lz77 self-check failed'
    return blob


def pendulane_icon():
    """32x32 banner icon: a pendulum bob on a rod swinging in front of a gear."""
    pal = [(0, 0, 0), (20, 16, 12), (70, 54, 36), (225, 170, 60), (180, 120, 50), (150, 150, 160),
           (240, 232, 210), (110, 70, 40)] + [(0, 0, 0)] * 8
    pix = [[1] * 32 for _ in range(32)]
    cx, cy = 16.0, 4.0
    gx, gy = 16.0, 22.0   # the gear behind: a ring with sixteen teeth
    for y in range(32):
        for x in range(32):
            r = math.hypot(x - gx, y - gy)
            ang = math.atan2(y - gy, x - gx)
            tooth = 1.6 if int(((ang + math.pi) / (2 * math.pi)) * 16) % 2 == 0 else 0.0
            if 6.0 <= r <= 9.0 + tooth:
                pix[y][x] = 2 if r < 8.0 else 4
    a = math.radians(24)   # the rod, swung to the left, and the bob
    bx, by = cx - 17 * math.sin(a), cy + 17 * math.cos(a)
    for i in range(0, 171):
        t = i / 10.0
        x, y = int(round(cx - t * math.sin(a))), int(round(cy + t * math.cos(a)))
        if 0 <= x < 32 and 0 <= y < 32:
            pix[y][x] = 5
    for y in range(32):
        for x in range(32):
            r = math.hypot(x - bx, y - by)
            if r <= 4.4:
                pix[y][x] = 3 if r < 3.2 else 7
            if r <= 1.6 and x < bx and y < by:
                pix[y][x] = 6
    for x in range(10, 23):
        pix[3][x] = 6
        pix[2][x] = 2
    return pix, pal


def write(path, data):
    with open(path, 'wb') as f:
        f.write(data)


def main():
    gen, nitro = sys.argv[1], sys.argv[2]
    os.makedirs(gen, exist_ok=True)
    os.makedirs(nitro, exist_ok=True)
    w = CWriter()

    # --- 2D ---------------------------------------------------------------
    w.blob('cv_font_tiles', images.font_tiles(), 'Font, 4bpp, chars 0x20-0x5F')
    w.blob('cv_ui_tiles', images.ui_tiles(), 'Window/gauge tiles, 4bpp')
    w.blob('cv_ui_pal', u16s([0]) + images.palette_bytes(images.UI_PALETTE)[2:])

    # --- Title ------------------------------------------------------------
    tiles, entries, pal = pdart.title_lettering()
    w.blob('cv_title_tiles', tiles, 'title lettering, 4bpp, %d x %d tiles' % (pdart.COLS, pdart.ROWS))
    w.blob('cv_title_map', u16s(entries), 'title lettering map entries, raster order, palette line %d' % pdart.PAL_LINE)
    w.blob('cv_title_pal', pal, 'title lettering palette line (16 colours)')
    w.define('PD_TITLE_COLS', pdart.COLS)
    w.define('PD_TITLE_ROWS', pdart.ROWS)
    w.define('PD_TITLE_PAL_LINE', pdart.PAL_LINE)
    w.define('PD_TITLE_BLANK', pdart.BLANK_TILE)
    w.define('PD_TITLE_PANEL', pdart.PANEL_TILE)
    bob, dot, objpal = pdart.sprites()
    w.blob('pd_bob_tiles', bob, 'pendulum bob sprite 32x32, 4bpp')
    w.blob('pd_dot_tiles', dot, 'pendulum rod dot sprite 8x8, 4bpp')
    w.blob('pd_obj_pal', objpal, 'title sprite palette line 0 (16 colours)')

    # --- Contraptions -----------------------------------------------------
    # The build stops when a contraption fails the checker (tools/pdorder/check.py).
    here = os.path.dirname(os.path.abspath(__file__))
    cs = pd_check.load(sorted(glob.glob(os.path.join(here, 'contraptions', 'ch*.txt'))))
    rows, ok = pd_check.check(cs)
    if not ok:
        for r in rows:
            for m in r['problems']:
                print('contraption %s: %s' % (r['id'], m), file=sys.stderr)
        sys.exit('contraptions failed the checker')
    stations = []        # (chapter, letter) -> index
    index = {}
    for ch in sorted(pd_model.CHAPTERS):
        for letter, (name, cost, _) in pd_model.CHAPTERS[ch][1].items():
            index[(ch, letter)] = len(stations)
            stations.append((name, cost))
    w.define('PD_MAXSLOTS', pd_model.MAX_SLOTS)
    w.define('PD_MAXOPT', pd_model.MAX_OPTS)
    w.define('PD_NUM_STATIONS', len(stations))
    w.define('PD_NUM_DEVICES', len(cs))
    w.define('PD_NUM_CHAPTERS', len(pd_model.CHAPTERS))
    w.raw_h('typedef struct { const char *name; uint16_t cost; } PdStation;')
    w.raw_h('typedef struct { const char *name; uint8_t chapter, nslots; uint16_t target; uint8_t par; uint8_t nopt[PD_MAXSLOTS];'
            ' uint8_t opt[PD_MAXSLOTS][PD_MAXOPT]; } PdDevice;')
    w.raw_h('extern const PdStation pd_stations[PD_NUM_STATIONS];')
    w.raw_h('extern const PdDevice pd_devices[PD_NUM_DEVICES];')
    w.raw_h('extern const char *const pd_chapter_name[PD_NUM_CHAPTERS];')
    w.raw_c('const PdStation pd_stations[PD_NUM_STATIONS] = {\n%s\n};\n'
            % '\n'.join('    { "%s", %d },' % st for st in stations))
    drows = []
    for c, r in zip(cs, rows):
        nopt = [len(x) for x in c.slots] + [0] * (pd_model.MAX_SLOTS - len(c.slots))
        opt = [[index[(c.chapter, ch)] for ch in x] + [0] * (pd_model.MAX_OPTS - len(x)) for x in c.slots]
        opt += [[0] * pd_model.MAX_OPTS] * (pd_model.MAX_SLOTS - len(c.slots))
        drows.append('    { "%s", %d, %d, %d, %d, { %s }, { %s } },' % (
            c.name, c.chapter, len(c.slots), c.target, r['par'], ', '.join(map(str, nopt)),
            ', '.join('{ %s }' % ', '.join(map(str, o)) for o in opt)))
    w.raw_c('const PdDevice pd_devices[PD_NUM_DEVICES] = {\n%s\n};\n' % '\n'.join(drows))
    w.raw_c('const char *const pd_chapter_name[PD_NUM_CHAPTERS] = { %s };\n'
            % ', '.join('"%s"' % pd_model.CHAPTERS[ch][0] for ch in sorted(pd_model.CHAPTERS)))

    # --- Sound ------------------------------------------------------------
    samples = audio.make_samples()
    for i, s in enumerate(samples):
        audio.SAMPLE_IDS[s.name] = i
        w.define('CV_SFX_%s' % s.name.upper(), i)
    songs = audio.make_songs()
    sample_rows = []
    for i, s in enumerate(samples):
        if s.data:
            w.blob('cv_smp_%s' % s.name, s.data)
            ptr = 'cv_smp_%s' % s.name
        else:
            ptr = '0'
        sample_rows.append('    { %s, %du, %du, %du, %d, %d },'
                           % (ptr, s.words, s.loop & 0xFFFF, s.rate & 0xFFFF, s.fmt, s.volume))
    song_rows = []
    for i, (name, tracks, tempo) in enumerate(songs):
        w.define('CV_SONG_%s' % name.upper(), i)
        ptrs = []
        for t, data in enumerate(tracks):
            if data:
                w.blob('cv_song_%s_%d' % (name, t), data)
                ptrs.append('cv_song_%s_%d' % (name, t))
            else:
                ptrs.append('0')
        song_rows.append('    { { %s }, %d, 0 },' % (', '.join(ptrs), tempo))
    w.define('CV_NUM_SAMPLES', len(samples))
    w.define('CV_NUM_SONGS', len(songs))
    w.raw_h('extern const CvSoundBank cv_sound_bank;')
    w.raw_c('static const CvSample samples[] = {\n%s\n};\n' % '\n'.join(sample_rows))
    w.raw_c('static const CvSong songs[] = {\n%s\n};\n' % '\n'.join(song_rows))
    w.raw_c('const CvSoundBank cv_sound_bank __attribute__((aligned(4))) = '
            '{ CV_BANK_MAGIC, %d, %d, samples, songs };\n' % (len(samples), len(songs)))
    names = ', '.join('"%s"' % s.name.upper() for s in samples)
    w.raw_h('extern const char *const cv_sample_names[];')
    w.raw_c('const char *const cv_sample_names[] = { %s };\n' % names)
    names = ', '.join('"%s"' % n.upper() for (n, _, _) in songs)
    w.raw_h('extern const char *const cv_song_names[];')
    w.raw_c('const char *const cv_song_names[] = { %s };\n' % names)

    # --- Cartridge files (NitroFS) ----------------------------------------
    # Licence texts are copied in by the Makefile. cart_init() checks the
    # probe file's CRC to find out whether NitroFS works on the cart in use.
    # The sound bench's ADPCM block: header (predictor 0, step index 50) and 32 samples of nibble 7 (the largest step up), so the
    # decoded output is non-zero from the first sample. Built here, not by an encoder: the bench needs a block of known timing.
    w.blob('pd_snd_adpcm', struct.pack('<hBB', 0, 50, 0) + b'\x77' * 16,
           'sound bench ADPCM block: header word + 32 samples (4 words)')
    w.define('CV_STREAM_RATE', 0)
    probe = bytes((i * 7 + 3) & 0xFF for i in range(2048))
    write(os.path.join(nitro, 'probe.bin'), probe)
    w.define('CV_PROBE_CRC16', '0x%04x' % codec.crc16(probe))

    w.write(gen)

    pix, pal = pendulane_icon()
    bmp_4bpp(os.path.join(gen, 'icon.bmp'), pix, pal)


if __name__ == '__main__':
    main()
