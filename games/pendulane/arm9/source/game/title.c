#include "gfx/text.h"

#define MAIN_BG ((u8 *)0x06000000)
#define MAIN_OBJ ((u8 *)0x06400000)
#define LETTER_CHAR_BASE 2     // 16 KB units: 0x06008000
#define LETTER_MAP_BLOCK 30    // 2 KB units: 0x0600F000
#define LETTER_ROW 5           // first map row of the lettering (rows 5-8, y 40-71)
#define PANEL_ROW 18           // rows 18-23 (y 144-191): the text sits on a dark panel
#define LETTER_COL ((32 - PD_TITLE_COLS) / 2)
#define BOB_TILE 0
#define DOT_TILE 16
#define PIVOT_X 128
#define PIVOT_Y 0
#define ROD 112                // pivot to the bob's centre
#define SWING_FRAMES 150       // one full swing there and back

_Static_assert(PD_TITLE_COLS <= 32, "the lettering must fit one map row");

static CvText main_text, sub_text;

static void load_art(void)
{
    swiCopy(cv_title_tiles, MAIN_BG + LETTER_CHAR_BASE * 0x4000, CV_TITLE_TILES_SIZE / 2 | COPY_MODE_HWORD);
    swiCopy(cv_title_pal, CV_PAL_BG_MAIN + PD_TITLE_PAL_LINE * 16, CV_TITLE_PAL_SIZE / 2 | COPY_MODE_HWORD);
    u16 *map = (u16 *)(MAIN_BG + LETTER_MAP_BLOCK * 2048);
    // Empty cells point at the blank tile (tile 0 is a lettering tile); rows 18-23 are a dark panel for the bottom text.
    for (int i = 0; i < 32 * 32; i++)
        map[i] = PD_TITLE_BLANK | PD_TITLE_PAL_LINE << 12;
    for (int i = PANEL_ROW * 32; i < 24 * 32; i++)
        map[i] = PD_TITLE_PANEL | PD_TITLE_PAL_LINE << 12;
    const u16 *src = (const u16 *)cv_title_map;
    for (int r = 0; r < PD_TITLE_ROWS; r++)
        for (int c = 0; c < PD_TITLE_COLS; c++)
            map[(LETTER_ROW + r) * 32 + LETTER_COL + c] = src[r * PD_TITLE_COLS + c];
    REG_BG1CNT = BG_TILE_BASE(LETTER_CHAR_BASE) | BG_MAP_BASE(LETTER_MAP_BLOCK) | BG_PRIORITY(2);
    REG_BG1HOFS = 0;
    REG_BG1VOFS = 0;

    swiCopy(pd_bob_tiles, MAIN_OBJ + BOB_TILE * 32, PD_BOB_TILES_SIZE / 2 | COPY_MODE_HWORD);
    swiCopy(pd_dot_tiles, MAIN_OBJ + DOT_TILE * 32, PD_DOT_TILES_SIZE / 2 | COPY_MODE_HWORD);
    swiCopy(pd_obj_pal, CV_PAL_OBJ_MAIN, PD_OBJ_PAL_SIZE / 2 | COPY_MODE_HWORD);
    REG_DISPCNT |= DISPLAY_BG1_ACTIVE | DISPLAY_SPR_ACTIVE | DISPLAY_SPR_1D;
}

// The pendulum at frame f: the swing angle follows a sine (about +-32 degrees), so it slows at the ends.
static void draw_pendulum(int f)
{
    int angle = (f * 32768 / SWING_FRAMES) & 0x7FFF;     // one turn = 32768
    int theta = sinLerp(angle) * 2950 / 4096;             // in 1/32768 turns: 2950 = 0.09 turn = 32 degrees
    int sx = sinLerp(theta), cx = cosLerp(theta);         // 4.12
    int bx = PIVOT_X + ROD * sx / 4096;
    int by = PIVOT_Y + ROD * cx / 4096;
    oam_clear(ENG_MAIN);
    for (int i = 1; i <= 12; i++)                        // the rod: a dot every 8 pixels
    {
        int d = i * 8 * ROD / 112;
        oam_add(ENG_MAIN, PIVOT_X + d * sx / 4096 - 4, PIVOT_Y + d * cx / 4096 - 4, SPR_8x8, DOT_TILE, 0, 1, 0, 0);
    }
    oam_add(ENG_MAIN, bx - 16, by - 12, SPR_32x32, BOB_TILE, 0, 1, 0, 0);
}

PdScene scene_title(void)
{
    scene_text_screens(&main_text, &sub_text);
    load_art();

    text_center(&main_text, 16, TP_GRAY, "AN AUTOMATON WORKSHOP");
    text_center(&main_text, 19, TP_WHITE, "START: THE WORKSHOP");
    text_center(&main_text, 21, TP_GRAY, "Y: BENCH LEDGER   X: CREDITS");

    text_center(&sub_text, 8, TP_WHITE, "APACHE-2.0 SOURCE");
    text_center(&sub_text, 10, TP_GRAY, "ALL ASSETS GENERATED BY CODE");
    text_printf(&sub_text, 1, 21, TP_GRAY, "ARM7 CORE: %s",
                sys_ipcsync_seen() == CV_SYNC_ARM7_READY ? "MOUNTED" : "WAITING");
    text_printf(&sub_text, 1, 22, TP_GRAY, "SAVE CHIP: %s", save_type_name());

    snd_bgm(CV_SONG_PENDULUM);
    fx_bright(FX_BOTH, -16);
    for (int f = 0;; f++)
    {
        // Fade in inside the loop (fx_fade_in() only waits for vblanks and would show the previous scene first).
        if (f < 20)
            fx_bright(FX_BOTH, -(16 * (19 - f) / 20));
        draw_pendulum(f);
        text_center(&main_text, 19, (f / 30) & 1 ? TP_GRAY : TP_WHITE, "START: THE WORKSHOP");
        scene_frame_end();
        if (qa_title_poll() || qa_marker_poll())
        {
            // Hidden auto QA mode (core/qa.h): the contraption list, like Start.
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_SELECT;
        }
        if (cv_in.pressed & KEY_START)
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_SELECT;
        }
        // The QA combo is L+R+X+Y: with L or R held X and Y are left alone (press L and R first).
        if ((cv_in.pressed & KEY_Y) && !(cv_in.held & (KEY_L | KEY_R)))
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_BENCH;
        }
        if ((cv_in.pressed & KEY_X) && !(cv_in.held & (KEY_L | KEY_R)))
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_CREDITS;
        }
    }
}
