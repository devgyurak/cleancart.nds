"""Generate every Buoyane asset.

    mkassets.py <gen_dir> <nitrofs_dir>

<gen_dir>/assets.c|h  data linked into the ARM9 binary
<gen_dir>/icon.bmp    banner icon for ndstool
<nitrofs_dir>/*       files loaded from the cartridge at run time

All output is a pure function of this source tree.
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from byroute import model as by_model, routes as by_routes  # noqa: E402
from cvtools import audio, codec, images  # noqa: E402
from cvtools.gfx import u16s, bmp_4bpp  # noqa: E402


class CWriter:
    def __init__(self):
        self.c = []
        self.h = []

    def blob(self, name, data, comment=''):
        data = bytes(data)
        while len(data) % 4:
            data += b'\0'
        if comment:
            self.h.append('// %s' % comment)
        self.h.append('extern const uint8_t %s[];' % name)
        self.h.append('#define %s_SIZE %du' % (name.upper(), len(data)))
        lines = []
        for i in range(0, len(data), 24):
            lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
        self.c.append('const uint8_t %s[] __attribute__((aligned(4))) = {\n%s\n};\n'
                      % (name, '\n'.join(lines)))

    def define(self, name, value):
        self.h.append('#define %s %s' % (name, value))

    def raw_h(self, text):
        self.h.append(text)

    def raw_c(self, text):
        self.c.append(text)

    def write(self, gen):
        hdr = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#ifndef CV_ASSETS_H', '#define CV_ASSETS_H', '',
               '#include <stdint.h>', '#include "cv_ipc.h"', '']
        with open(os.path.join(gen, 'assets.h'), 'w') as f:
            f.write('\n'.join(hdr + self.h + ['', '#endif', '']))
        src = ['// SPDX-License-Identifier: Apache-2.0',
               '// Generated by tools/mkassets.py. Do not edit.',
               '#include "assets.h"', '']
        with open(os.path.join(gen, 'assets.c'), 'w') as f:
            f.write('\n'.join(src) + '\n' + '\n'.join(self.c))


def pack(parts):
    """CVPK container: u32 magic, u32 count, {u32 off, u32 size}[count], data."""
    out = bytearray(struct.pack('<II', 0x4B505643, len(parts)))
    table_at = len(out)
    out += b'\0' * (8 * len(parts))
    for i, p in enumerate(parts):
        while len(out) % 4:
            out.append(0)
        struct.pack_into('<II', out, table_at + 8 * i, len(out), len(p))
        out += p
    while len(out) % 4:
        out.append(0)
    return bytes(out)


def lz(data):
    blob = codec.lz77(data)
    assert codec.lz77_decode(blob) == bytes(data), 'lz77 self-check failed'
    return blob


def buoyane_icon():
    """32x32 banner icon: a red and white can buoy on dark water under a night sky."""
    pal = [(0, 0, 0), (6, 10, 30), (14, 24, 60), (225, 40, 40), (240, 240, 245), (250, 220, 90),
           (40, 60, 110), (90, 120, 170)] + [(0, 0, 0)] * 8
    pix = [[1] * 32 for _ in range(32)]
    for y in range(32):
        for x in range(32):
            if y >= 20:
                pix[y][x] = 2 if (x + y // 2) % 7 else 6          # water, a few ripples
    for y in range(8, 24):                                          # the buoy: a can with a red top and white band
        half = 4 if y < 20 else 5 - (y - 20)
        for x in range(16 - half, 16 + half):
            pix[y][x] = 3 if y < 13 or y >= 18 else 4
    for y in range(3, 8):                                           # the mast and its lamp
        pix[y][16] = 4
    for y in range(1, 4):
        for x in range(15, 18):
            pix[y][x] = 5
    return pix, pal


def write(path, data):
    with open(path, 'wb') as f:
        f.write(data)


def main():
    gen, nitro = sys.argv[1], sys.argv[2]
    os.makedirs(gen, exist_ok=True)
    os.makedirs(nitro, exist_ok=True)
    w = CWriter()

    # --- 2D ---------------------------------------------------------------
    w.blob('cv_font_tiles', images.font_tiles(), 'Font, 4bpp, chars 0x20-0x5F')
    w.blob('cv_ui_tiles', images.ui_tiles(), 'Window/gauge tiles, 4bpp')
    w.blob('cv_ui_pal', u16s([0]) + images.palette_bytes(images.UI_PALETTE)[2:])

    # --- Routes and the almanac ---------------------------------------------
    # The build stops when a route is not solvable from the almanac (tools/byroute/routes.py).
    here = os.path.dirname(os.path.abspath(__file__))
    try:
        chapters = by_routes.load_all(os.path.join(here, 'routes'))
    except by_routes.RouteError as e:
        sys.exit('route files failed the checker:\n%s' % e)
    blob = by_routes.pack(chapters)
    w.blob('cv_routes', blob, 'routes: chapters x approaches x gates x (view, true, a, b, c), tools/byroute/routes.py')
    w.define('BY_CHAPTERS', by_model.NCHAPTERS)
    w.define('BY_APPROACHES', by_routes.APPROACHES)
    w.define('BY_GATES', by_routes.GATES)
    w.define('BY_TYPES', by_model.NTYPES)
    w.define('BY_VIEWS', by_model.NVIEWS)
    w.define('BY_PLAN_HASH', '0x%08xu' % by_routes.plan_hash(blob))
    w.raw_h('extern const char *const by_chapter_name[BY_CHAPTERS];')
    w.raw_c('const char *const by_chapter_name[BY_CHAPTERS] = { %s };\n'
            % ', '.join('"%s"' % c for c in by_model.CHAPTERS))
    w.raw_h('extern const char *const by_approach_name[BY_CHAPTERS][BY_APPROACHES];')
    rows = ['    { %s },' % ', '.join('"%s"' % n.upper() for n in names)
            for names in by_routes.approach_names(chapters)]
    w.raw_c('const char *const by_approach_name[BY_CHAPTERS][BY_APPROACHES] = {\n%s\n};\n' % '\n'.join(rows))
    # the almanac: look[chapter][type][view], and the numbers the 3D lights are drawn from
    w.raw_h('extern const uint8_t by_look[BY_CHAPTERS][BY_TYPES][BY_VIEWS];')
    w.raw_c('const uint8_t by_look[BY_CHAPTERS][BY_TYPES][BY_VIEWS] = {\n%s\n};\n' % '\n'.join(
        '    { %s },' % ', '.join('{ %s }' % ', '.join(str(v) for v in t) for t in ch) for ch in by_model.table()))

    def table(name, values, ctype='uint8_t'):
        w.raw_h('extern const %s %s[%d];' % (ctype, name, len(values)))
        w.raw_c('const %s %s[%d] = { %s };\n' % (ctype, name, len(values), ', '.join(str(v) for v in values)))

    table('by_range_w', by_model.RANGE_W)
    table('by_range_cut', by_model.RANGE_CUT)
    table('by_sect_first', by_model.SECT_FIRST)
    table('by_sect_w1', by_model.SECT_W1)
    table('by_sect_w2', by_model.SECT_W2)
    table('by_sect_cut', by_model.SECT_CUT)
    table('by_fog_bucket', by_model.FOG_BUCKET)
    w.raw_h('extern const uint8_t by_fog_density[BY_VIEWS][BY_TYPES];')
    w.raw_c('const uint8_t by_fog_density[BY_VIEWS][BY_TYPES] = { %s };\n'
            % ', '.join('{ %s }' % ', '.join(str(v) for v in row) for row in by_model.FOG_DENSITY))
    table('by_edge_a', by_model.EDGE_A)
    table('by_edge_b', by_model.EDGE_B)
    table('by_harbour_gap', by_model.HARBOUR_GAP)

    # --- Sound ------------------------------------------------------------
    samples = audio.make_samples()
    for i, s in enumerate(samples):
        audio.SAMPLE_IDS[s.name] = i
        w.define('CV_SFX_%s' % s.name.upper(), i)
    songs = audio.make_songs()
    sample_rows = []
    for i, s in enumerate(samples):
        if s.data:
            w.blob('cv_smp_%s' % s.name, s.data)
            ptr = 'cv_smp_%s' % s.name
        else:
            ptr = '0'
        sample_rows.append('    { %s, %du, %du, %du, %d, %d },'
                           % (ptr, s.words, s.loop & 0xFFFF, s.rate & 0xFFFF, s.fmt, s.volume))
    song_rows = []
    for i, (name, tracks, tempo) in enumerate(songs):
        w.define('CV_SONG_%s' % name.upper(), i)
        ptrs = []
        for t, data in enumerate(tracks):
            if data:
                w.blob('cv_song_%s_%d' % (name, t), data)
                ptrs.append('cv_song_%s_%d' % (name, t))
            else:
                ptrs.append('0')
        song_rows.append('    { { %s }, %d, 0 },' % (', '.join(ptrs), tempo))
    w.define('CV_NUM_SAMPLES', len(samples))
    w.define('CV_NUM_SONGS', len(songs))
    w.raw_h('extern const CvSoundBank cv_sound_bank;')
    w.raw_c('static const CvSample samples[] = {\n%s\n};\n' % '\n'.join(sample_rows))
    w.raw_c('static const CvSong songs[] = {\n%s\n};\n' % '\n'.join(song_rows))
    w.raw_c('const CvSoundBank cv_sound_bank __attribute__((aligned(4))) = '
            '{ CV_BANK_MAGIC, %d, %d, samples, songs };\n' % (len(samples), len(songs)))
    names = ', '.join('"%s"' % s.name.upper() for s in samples)
    w.raw_h('extern const char *const cv_sample_names[];')
    w.raw_c('const char *const cv_sample_names[] = { %s };\n' % names)
    names = ', '.join('"%s"' % n.upper() for (n, _, _) in songs)
    w.raw_h('extern const char *const cv_song_names[];')
    w.raw_c('const char *const cv_song_names[] = { %s };\n' % names)

    # --- Cartridge files (NitroFS) ----------------------------------------
    # Licence texts are copied in by the Makefile. cart_init() checks the
    # probe file's CRC to find out whether NitroFS works on the cart in use.
    w.define('CV_STREAM_RATE', 0)
    probe = bytes((i * 7 + 3) & 0xFF for i in range(2048))
    write(os.path.join(nitro, 'probe.bin'), probe)
    w.define('CV_PROBE_CRC16', '0x%04x' % codec.crc16(probe))

    w.write(gen)

    pix, pal = buoyane_icon()
    bmp_4bpp(os.path.join(gen, 'icon.bmp'), pix, pal)


if __name__ == '__main__':
    main()
