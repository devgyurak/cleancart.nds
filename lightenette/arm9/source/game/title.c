#define MAIN_BG ((u8 *)0x06000000)
#define SUB_BG  ((u8 *)0x06200000)

static CvText main_text, sub_text;

static void frame_end(void)
{
    oam_commit();
    sys_vsync();
    sys_handle_lid();
    input_update();
}

// One engine: BG0 text with the font at tile 0 and the map at block 31.
static void setup_text(CvText *t, vu32 *dispcnt, vu16 *bg0cnt, u8 *bg, u16 *pal, u16 back)
{
    *dispcnt = MODE_0_2D | DISPLAY_BG0_ACTIVE;
    *bg0cnt = 0 | (0 << 2) | (31 << 8);
    text_load_tiles(bg);
    text_load_palette(pal);
    pal[0] = back;
    text_init(t, (u16 *)(bg + 31 * 2048), 0);
    text_clear(t);
}

LtScene scene_title(void)
{
    display_reset();
    vram_layout(VL_MENU);
    setup_text(&main_text, &REG_DISPCNT, &REG_BG0CNT, MAIN_BG, CV_PAL_BG_MAIN, RGB15(1, 1, 4));
    setup_text(&sub_text, &REG_DISPCNT_SUB, &REG_BG0CNT_SUB, SUB_BG, CV_PAL_BG_SUB, RGB15(2, 2, 6));

    text_center(&main_text, 8, TP_YELLOW, "LIGHTENETTE");
    text_center(&main_text, 10, TP_GRAY, "LANTERN AND MARIONETTE PUZZLE");
    text_center(&main_text, 21, TP_GRAY, "PRESS START");
    text_center(&main_text, 23, TP_GRAY, "SELECT: TEST MENU");

    text_center(&sub_text, 8, TP_WHITE, "APACHE-2.0 SOURCE");
    text_center(&sub_text, 10, TP_GRAY, "ALL ASSETS GENERATED BY CODE");
    text_printf(&sub_text, 1, 21, TP_GRAY, "ARM7 CORE: %s",
                sys_ipcsync_seen() == CV_SYNC_ARM7_READY ? "MOUNTED" : "WAITING");
    text_printf(&sub_text, 1, 22, TP_GRAY, "SAVE CHIP: %s", save_type_name());

    fx_bright(FX_BOTH, -16);
    fx_fade_in(FX_BOTH, 20, false);
    for (int f = 0;; f++)
    {
        // Blink the prompt.
        text_center(&main_text, 21, (f / 30) & 1 ? TP_GRAY : TP_WHITE, "PRESS START");
        frame_end();
        if (cv_in.pressed & KEY_START)
            return SC_ACT1;
        if (cv_in.pressed & KEY_SELECT)
            return SC_MENU;
    }
}

// Test menu: the accuracy judge, acts 2 and 3 and the rehearsal.
LtScene scene_menu(void)
{
    static const char *const items[] = { "ACCURACY JUDGE", "ACT 2: TURN THE DOLLS", "ACT 3: FIND THE MARKS", "REHEARSAL: ACTS 1-3" };
    static const LtScene targets[] = { SC_JUDGE, SC_ACT2, SC_ACT3, SC_REHEARSAL };
    enum { N = sizeof(items) / sizeof(items[0]) };

    display_reset();
    vram_layout(VL_MENU);
    setup_text(&main_text, &REG_DISPCNT, &REG_BG0CNT, MAIN_BG, CV_PAL_BG_MAIN, RGB15(1, 1, 4));
    setup_text(&sub_text, &REG_DISPCNT_SUB, &REG_BG0CNT_SUB, SUB_BG, CV_PAL_BG_SUB, RGB15(2, 2, 6));
    text_center(&main_text, 4, TP_YELLOW, "TEST MENU");
    text_center(&sub_text, 8, TP_GRAY, "UP/DOWN: CHOOSE   A: START");
    text_center(&sub_text, 10, TP_GRAY, "B: BACK");
    text_center(&sub_text, 14, TP_GRAY, "NEEDS NO CART FILES OR SAVE CHIP");
    fx_bright(FX_BOTH, 0);

    int sel = 0;
    for (;;)
    {
        for (int i = 0; i < N; i++)
            text_printf(&main_text, 6, 9 + 2 * i, i == sel ? TP_YELLOW : TP_GRAY, "%c %-22s",
                        i == sel ? '>' : ' ', items[i]);
        frame_end();
        if (cv_in.pressed & KEY_UP)
            sel = (sel + N - 1) % N;
        if (cv_in.pressed & KEY_DOWN)
            sel = (sel + 1) % N;
        if (cv_in.pressed & KEY_A)
            return targets[sel];
        if (cv_in.pressed & KEY_B)
            return SC_TITLE;
    }
}
