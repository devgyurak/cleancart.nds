#define MAIN_BG ((u8 *)0x06000000)
#define SUB_BG  ((u8 *)0x06200000)
#define TITLE_BMP_BASE 4   // 16 KB units: 0x06010000, above the font and map
#define TITLE_PAL_FIRST 96 // palette entries 0-95 belong to the text layer

static CvText main_text, sub_text;

LtScene scene_title(void)
{
    scene_text_screens(&main_text, &sub_text);

    // BG3: 256x192 8bpp bitmap; BG0 text stays on top of it.
    lz_to_vram(cv_title_lz, MAIN_BG + TITLE_BMP_BASE * 0x4000);
    swiCopy(cv_title_pal, CV_PAL_BG_MAIN + TITLE_PAL_FIRST, (CV_TITLE_PAL_SIZE / 2) | COPY_MODE_HWORD);
    REG_BG3CNT = BG_BMP8_256x256 | BG_BMP_BASE(TITLE_BMP_BASE) | 1;
    REG_BG3PA = 256;
    REG_BG3PB = 0;
    REG_BG3PC = 0;
    REG_BG3PD = 256;
    REG_BG3X = 0;
    REG_BG3Y = 0;
    REG_DISPCNT = MODE_5_2D | DISPLAY_BG0_ACTIVE | DISPLAY_BG3_ACTIVE;

    text_center(&main_text, 18, TP_GRAY, "LANTERN AND MARIONETTE PUZZLE");
    text_center(&main_text, 21, TP_GRAY, "PRESS START");
    text_center(&main_text, 23, TP_GRAY, "X: CREDITS   SELECT: TEST MENU");

    text_center(&sub_text, 8, TP_WHITE, "APACHE-2.0 SOURCE");
    text_center(&sub_text, 10, TP_GRAY, "ALL ASSETS GENERATED BY CODE");
    text_printf(&sub_text, 1, 21, TP_GRAY, "ARM7 CORE: %s",
                sys_ipcsync_seen() == CV_SYNC_ARM7_READY ? "MOUNTED" : "WAITING");
    text_printf(&sub_text, 1, 22, TP_GRAY, "SAVE CHIP: %s", save_type_name());

    snd_bgm(CV_SONG_LANTERN);
    fx_bright(FX_BOTH, -16);
    fx_fade_in(FX_BOTH, 20, false);
    for (int f = 0;; f++)
    {
        // Blink the prompt.
        text_center(&main_text, 21, (f / 30) & 1 ? TP_GRAY : TP_WHITE, "PRESS START");
        scene_frame_end();
        if (qa_title_poll())
        {
            // Hidden auto QA mode (core/qa.h): the normal flow from act 1, left like Start.
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return SC_ACT1;
        }
        // X opens the credits, but L+R+X is the start of the QA combo: with L or R
        // held X is left alone (press L and R first, then X).
        u16 menu_keys = KEY_START | KEY_SELECT | ((cv_in.held & (KEY_L | KEY_R)) ? 0 : KEY_X);
        if (cv_in.pressed & menu_keys)
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            snd_bgm_stop();
            return (cv_in.pressed & KEY_START) ? SC_ACT1 : (cv_in.pressed & KEY_X) ? SC_CREDITS : SC_MENU;
        }
    }
}

// Test menu: the accuracy judge, acts 2 to 5 and the rehearsal.
LtScene scene_menu(void)
{
    static const char *const items[] = { "ACCURACY JUDGE", "ACT 2: TURN THE DOLLS", "ACT 3: FIND THE MARKS", "ACT 4: UNTANGLE", "ACT 5: THE FINALE", "REHEARSAL: ACTS 1-5", "CREDITS AND LICENCES" };
    static const LtScene targets[] = { SC_JUDGE, SC_ACT2, SC_ACT3, SC_ACT4, SC_ACT5, SC_REHEARSAL, SC_CREDITS };
    enum { N = sizeof(items) / sizeof(items[0]) };

    scene_text_screens(&main_text, &sub_text);
    text_center(&main_text, 4, TP_YELLOW, "TEST MENU");
    text_center(&sub_text, 8, TP_GRAY, "UP/DOWN: CHOOSE   A: START");
    text_center(&sub_text, 10, TP_GRAY, "B: BACK");
    text_center(&sub_text, 14, TP_GRAY, "NEEDS NO CART FILES OR SAVE CHIP");
    fx_bright(FX_BOTH, 0);

    int sel = 0;
    for (;;)
    {
        for (int i = 0; i < N; i++)
            text_printf(&main_text, 6, 9 + 2 * i, i == sel ? TP_YELLOW : TP_GRAY, "%c %-22s",
                        i == sel ? '>' : ' ', items[i]);
        scene_frame_end();
        if (cv_in.pressed & (KEY_UP | KEY_DOWN))
            snd_sfx(CV_SFX_CLICK, 80, 64);
        if (cv_in.pressed & KEY_UP)
            sel = (sel + N - 1) % N;
        if (cv_in.pressed & KEY_DOWN)
            sel = (sel + 1) % N;
        if (cv_in.pressed & KEY_A)
            return targets[sel];
        if (cv_in.pressed & KEY_B)
            return SC_TITLE;
    }
}
