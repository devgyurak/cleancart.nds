#include <nds.h>

#include "assets.h"
#include "core/input.h"
#include "core/qa.h"
#include "core/save.h"
#include "core/snd.h"
#include "core/sys.h"
#include "game/scenes.h"
#include "gfx/fx.h"
#include "gfx/text.h"

static CvText main_text, sub_text;

EvScene scene_title(void)
{
    scene_text_screens(&main_text, &sub_text);
    REG_DISPCNT = MODE_0_2D | DISPLAY_BG0_ACTIVE;

    text_center(&main_text, 8, TP_YELLOW, "ELEVANE");
    text_center(&main_text, 10, TP_GRAY, "A VOXEL SILHOUETTE PUZZLE");
    text_center(&main_text, 19, TP_WHITE, "PRESS START");
    text_center(&main_text, 21, TP_GRAY, "X: CREDITS");

    text_center(&sub_text, 8, TP_WHITE, "APACHE-2.0 SOURCE");
    text_center(&sub_text, 10, TP_GRAY, "ALL ASSETS GENERATED BY CODE");
    text_printf(&sub_text, 1, 21, TP_GRAY, "ARM7 CORE: %s",
                sys_ipcsync_seen() == CV_SYNC_ARM7_READY ? "MOUNTED" : "WAITING");
    text_printf(&sub_text, 1, 22, TP_GRAY, "SAVE CHIP: %s", save_type_name());

    fx_bright(FX_BOTH, -16);
    fx_fade_in(FX_BOTH, 20, false);
    for (;;)
    {
        scene_frame_end();
        if (qa_title_poll())
        {
            // Hidden auto QA mode (core/qa.h): left like X.
            snd_sfx(CV_SFX_CHIME, 100, 64);
            return SC_CREDITS;
        }
        // X opens the credits, but L+R+X is the start of the QA combo: with L or R
        // held X is left alone (press L and R first, then X).
        if (cv_in.pressed & KEY_START)
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            return SC_SELECT;
        }
        if ((cv_in.pressed & KEY_X) && !(cv_in.held & (KEY_L | KEY_R)))
        {
            snd_sfx(CV_SFX_CHIME, 100, 64);
            return SC_CREDITS;
        }
    }
}
