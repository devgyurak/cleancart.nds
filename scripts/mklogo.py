"""Writes the repository logo to docs/logo/.

The mark is an unlocked game card: the padlock body is a card (corner notch,
contact slots instead of a keyhole) and the shackle is open. The wordmark
"CLEANCART.NDS" is set in Corvane's own 5x7 pixel font
(corvane/tools/cvtools/font.py), so no third-party font is involved.

    python3 scripts/mklogo.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'corvane', 'tools'))
from cvtools.font import GLYPHS  # noqa: E402

OUT = os.path.join(ROOT, 'docs', 'logo')
NAME = 'CLEANCART.NDS'
INK = {'': '#000000', '-dark': '#ffffff'}


def rect(x, y, w, h):
    return f'M{x} {y}h{w}v{h}h{-w}z'


# 256x256 mark.
CARD = ('M62 108H178L208 138V218A14 14 0 0 1 194 232H62A14 14 0 0 1 48 218V122A14 14 0 0 1 62 108Z'
        + ''.join(rect(67 + i * 22, 186, 12, 28) for i in range(6)))
SHACKLE = 'M76 112V72A52 52 0 0 1 180 72V86H156V72A28 28 0 0 0 100 72V112Z'


def wordmark(text, px, x0, y0, bold):
    """Pixel text as one path; horizontal runs of ink merged into one rect.

    Each run is widened by `bold` units to the right: vertical strokes get
    heavier while horizontals keep their height (optical weight next to the mark).
    """
    d = []
    for ci, ch in enumerate(text):
        for r, row in enumerate(GLYPHS[ch]):
            c = 0
            while c < 5:
                if row[c] != '#':
                    c += 1
                    continue
                e = c
                while e < 5 and row[e] == '#':
                    e += 1
                d.append(rect(x0 + (ci * 6 + c) * px, y0 + r * px, (e - c) * px + bold, px))
                c = e
    return ''.join(d)


def svg(w, h, ink, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="cleancart.nds">\n'
            '<!-- SPDX-License-Identifier: Apache-2.0 -->\n'
            '<!-- SPDX-FileCopyrightText: 2026 Corvane contributors -->\n'
            '<!-- Generated by scripts/mklogo.py -->\n'
            '<title>cleancart.nds</title>\n'
            f'<g fill="{ink}">\n{body}</g>\n</svg>\n')


def main():
    os.makedirs(OUT, exist_ok=True)
    mark = f'<path fill-rule="evenodd" d="{CARD}"/>\n<path d="{SHACKLE}"/>\n'
    px, bold, gap = 16, 6, 48
    text_w = (len(NAME) * 6 - 1) * px + bold
    words = f'<path d="{wordmark(NAME, px, 256 + gap, (256 - 7 * px) // 2, bold)}"/>\n'
    for suffix, ink in INK.items():
        files = {
            f'cleancart-mark{suffix}.svg': svg(256, 256, ink, mark),
            f'cleancart-lockup{suffix}.svg': svg(256 + gap + text_w, 256, ink, mark + words),
        }
        for name, text in files.items():
            with open(os.path.join(OUT, name), 'w', newline='\n') as f:
                f.write(text)
            print('wrote', os.path.relpath(os.path.join(OUT, name), ROOT))


if __name__ == '__main__':
    main()
