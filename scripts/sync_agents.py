"""Generate Codex custom agents (.codex/agents/*.toml) from the canonical
Claude Code subagents (.claude/agents/*.md).

    python3 scripts/sync_agents.py          # write
    python3 scripts/sync_agents.py --check  # exit 1 if out of date

Codex needs name, description and developer_instructions. Claude's `tools`
and `model` fields have no Codex equivalent; the tool limits are restated in
the instructions instead.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '.claude', 'agents')
DST = os.path.join(ROOT, '.codex', 'agents')


def parse(path):
    text = open(path).read()
    if not text.startswith('---\n'):
        raise ValueError('%s: missing frontmatter' % path)
    head, body = text[4:].split('\n---\n', 1)
    meta = {}
    for line in head.splitlines():
        if ':' in line:
            k, v = line.split(':', 1)
            meta[k.strip()] = v.strip()
    return meta, body.strip()


def toml_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(meta, body):
    tools = meta.get('tools', '')
    note = ''
    if tools and 'Edit' not in tools and 'Write' not in tools:
        note = 'You are read-only: do not modify files.\n\n'
    instructions = note + body
    if '"""' in instructions:
        raise ValueError('instructions may not contain """')
    return ('# Generated by scripts/sync_agents.py from .claude/agents/%s.md - do not edit.\n'
            'name = %s\n'
            'description = %s\n'
            'developer_instructions = """\n%s\n"""\n'
            % (meta['name'], toml_str(meta['name']), toml_str(meta['description']), instructions))


def main(argv):
    check = '--check' in argv
    os.makedirs(DST, exist_ok=True)
    stale = []
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith('.md'):
            continue
        meta, body = parse(os.path.join(SRC, fn))
        out = os.path.join(DST, meta['name'] + '.toml')
        content = render(meta, body)
        old = open(out).read() if os.path.exists(out) else None
        if old != content:
            stale.append(out)
            if not check:
                with open(out, 'w') as f:
                    f.write(content)
    for p in stale:
        print(('stale: ' if check else 'wrote: ') + os.path.relpath(p, ROOT))
    return 1 if check and stale else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
